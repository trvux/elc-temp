import importlib.util
import unittest
from pathlib import Path

HERE = Path(__file__).parent


def load(name, file):
    spec = importlib.util.spec_from_file_location(name, HERE / file)
    mod = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(mod)
    return mod


live = load("live", "live.py")
legacy = load("import_legacy_redirects", "import_legacy_redirects.py")

LIVE = {"/", "/dich-vu", "/dich-vu/moi", "/dich-vu/khac", "/tin-tuc/bai-moi"}


class BuildRedirects(unittest.TestCase):
    def test_plain_redirect_is_kept(self):
        table, skipped = live.build_redirects([("/dich-vu/cu", "/dich-vu/moi")], LIVE)
        self.assertEqual(table, {"/dich-vu/cu": "/dich-vu/moi"})
        self.assertEqual(skipped, [])

    def test_trailing_slashes_are_normalised(self):
        table, _ = live.build_redirects([("/dich-vu/cu/", "/dich-vu/moi/")], LIVE)
        self.assertEqual(table, {"/dich-vu/cu": "/dich-vu/moi"})

    def test_source_that_is_a_live_page_is_skipped(self):
        # A redirect on a live URL would hide a real page: must never reach nginx.
        table, skipped = live.build_redirects([("/dich-vu/khac", "/dich-vu/moi")], LIVE)
        self.assertEqual(table, {})
        self.assertEqual(skipped, [("/dich-vu/khac", "source is a live page")])

    def test_target_that_is_not_live_is_skipped(self):
        table, skipped = live.build_redirects([("/cu", "/khong-con-song")], LIVE)
        self.assertEqual(table, {})
        self.assertEqual(skipped, [("/cu", "target is not live")])

    def test_external_target_is_allowed(self):
        table, _ = live.build_redirects([("/cu", "https://example.com/x")], LIVE)
        self.assertEqual(table, {"/cu": "https://example.com/x"})

    def test_chain_is_flattened_to_the_final_target(self):
        rows = [("/a", "/b"), ("/b", "/dich-vu/moi")]
        table, _ = live.build_redirects(rows, LIVE)
        self.assertEqual(table, {"/a": "/dich-vu/moi", "/b": "/dich-vu/moi"})

    def test_loop_is_dropped_not_emitted(self):
        table, skipped = live.build_redirects([("/a", "/b"), ("/b", "/a")], LIVE)
        self.assertEqual(table, {})
        self.assertEqual(sorted(s[0] for s in skipped), ["/a", "/b"])


class RenderRedirects(unittest.TestCase):
    def test_emits_both_slash_variants_in_nginx_map_syntax(self):
        text = live.render_redirects({"/dich-vu/cu": "/dich-vu/moi"})
        self.assertIn("map $uri $elc_redir {", text)
        self.assertIn('    default "";', text)
        self.assertIn('    "/dich-vu/cu" "/dich-vu/moi";', text)
        self.assertIn('    "/dich-vu/cu/" "/dich-vu/moi";', text)

    def test_quotes_and_backslashes_are_escaped(self):
        text = live.render_redirects({'/a"b': "/c\\d"})
        self.assertIn('"/a\\"b"', text)
        self.assertIn('"/c\\\\d"', text)


class LegacyImport(unittest.TestCase):
    SAMPLE = """# GENERATED by scripts/nginx-live/redirects.py - do not edit.
map $uri $elc_redir {
    default "";
    "/about" "/gioi-thieu";
    "/about/" "/gioi-thieu";
    "/chi-nhanh/kho" "/thong-tin";
    "/chi-nhanh/kho/" "/thong-tin";
}
"""

    def test_slash_variants_collapse_to_one_row(self):
        self.assertEqual(legacy.parse(self.SAMPLE), {"/about": "/gioi-thieu", "/chi-nhanh/kho": "/thong-tin"})

    def test_roundtrip_through_the_generator_gives_the_same_map(self):
        pairs = legacy.parse(self.SAMPLE)
        live_paths = {"/", "/gioi-thieu", "/thong-tin"}
        table, _ = live.build_redirects(sorted(pairs.items()), live_paths)
        again = legacy.parse(live.render_redirects(table))
        self.assertEqual(again, pairs)

    def test_sql_is_idempotent_and_skips_junk(self):
        sql = legacy.to_sql(legacy.parse(self.SAMPLE + '    "/" "/x";\n    "/same" "/same";\n'))
        self.assertIn("ON CONFLICT (from_path) DO NOTHING", sql)
        self.assertNotIn("$q$/$q$", sql)
        self.assertNotIn("/same", sql)


if __name__ == "__main__":
    unittest.main()
