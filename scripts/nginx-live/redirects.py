#!/usr/bin/env python3
"""Build elc-redirects.conf ($elc_redir): 308 only for legacy URLs that ever had GSC impressions
and whose final target is live. Everything else stays 410.

Usage: python3 redirects.py <live.json> <gsc pages_all.csv> <out.conf>
"""
import csv, json, re, sys, urllib.parse
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
live = set(json.load(open(sys.argv[1])))
gsc, out = sys.argv[2], sys.argv[3]


def norm(p):
    return urllib.parse.unquote(p.split('#')[0].split('?')[0]).rstrip('/') or '/'


seen = {norm(r['page'].split('.vn', 1)[-1] or '/') for r in csv.DictReader(open(gsc)) if int(r['impressions']) > 0}
cand = {}
for a, b in re.findall(r'source:\s*"([^"]+)",\s*destination:\s*"([^"]+)"', (ROOT / 'next.config.ts').read_text()):
    if ':' not in a and '*' not in a:
        cand[norm(a)] = norm(b)
for a, b in json.load(open(ROOT / 'shared/redirects-map.json')).items():
    if a != '/$' and not a.startswith('/cdn-cgi'):
        cand.setdefault(norm(a), norm(b))
for s in [p.split('/')[-1] for p in live if p.startswith('/thong-tin/')]:
    cand[f'/chi-nhanh/{s}'] = cand[f'/co-so-ha-tang/{s}'] = f'/thong-tin/{s}'
cand['/chi-nhanh'] = cand['/co-so-ha-tang'] = '/thong-tin'


def final(p, seen_=()):
    d = cand.get(p)
    return p if d is None or p in seen_ else final(d, seen_ + (p,))


# Legacy multi-segment rules that used to live in shared/proxy.ts (now shadowed by nginx):
#   /san-pham/{...}/{prod} -> /san-pham/{prod},  /du-an/{...}/{slug} -> /du-an/{slug}
for a in seen:
    parts = [x for x in a.split('/') if x]
    if len(parts) >= 3 and parts[0] in ('san-pham', 'du-an') and a not in cand:
        cand[a] = f'/{parts[0]}/{parts[-1]}'

HUBS = {'/san-pham', '/du-an', '/tin-tuc', '/dich-vu'}   # generic hub = soft-404 -> 410
WEAK = {'/san-pham/may-lanh', '/san-pham/daikin', '/san-pham/menred', '/san-pham/lg', '/san-pham/acis'}  # broad brand/group
EQUIV_ROOTS = ('/san-pham/', '/du-an/', '/thong-tin/', '/chi-nhanh', '/co-so-ha-tang', '/danh-muc/')
explicit = {norm(a) for a, _ in re.findall(r'source:\s*"([^"]+)",\s*destination:\s*"([^"]+)"', (ROOT / 'next.config.ts').read_text())}


def relevant(a, f):
    """Redirect only when the destination is a real equivalent of the source; otherwise 410.
    - Hand-written rules in next.config.ts are trusted (renamed slugs / merged pages).
    - Auto-mapped legacy URLs: must come from the product/project/branch/category trees, and the
      destination can't be a hub or a broad brand/group page (that is a soft-404).
    - Root WP blog slugs (how-tos, "x la gi", fault codes) have no equivalent page -> 410.
    """
    if f in HUBS:
        return False
    if a in explicit:
        return True
    return a.startswith(EQUIV_ROOTS) and f not in WEAK


red = {a: final(b) for a, b in cand.items()
       if a not in live and (a in seen or a.startswith(('/chi-nhanh', '/co-so-ha-tang')))
       and final(b) in live and final(b) != a and relevant(a, final(b))}
# Always-on aliases for AI-agent trust-anchor probes (no GSC history needed). Targets must be live.
AGENT_ALIASES = {
    '/about': '/gioi-thieu-ve-dien-may-elc',
    '/contact': '/thong-tin',
    '/privacy': '/chinh-sach-thu-thap-va-xu-ly-du-lieu-ca-nhan',
}
for a, b in AGENT_ALIASES.items():
    if b in live:
        red[a] = b
L = ['# GENERATED by scripts/nginx-live/redirects.py - do not edit.', 'map $uri $elc_redir {', '    default "";']
for a, b in sorted(red.items()):
    for k in ([a] if a == '/' else [a, a + '/']):
        L.append('    "%s" "%s";' % (k.replace('"', '\\"'), urllib.parse.quote(b)))
L.append('}')
Path(out).write_text('\n'.join(L) + '\n')
print(len(red), 'redirects')
